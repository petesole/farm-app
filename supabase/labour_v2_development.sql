-- JSPL Labour v1: development-branch preparation; NOT YET APPLIED TO SHARED SUPABASE
-- Access sources: LabourT, LabourActivityT, LabourDepartmentT, LabourBudgetT,
-- LabourDailyQ and LabourWeeklyAOQ.
-- Apply only after development database/isolated schema is configured.
begin;
create table if not exists public.labour_department_v2 (
  labour_department_id bigint primary key,
  labour_department text not null
);
create table if not exists public.labour_activity_v2 (
  labour_activity_id bigint primary key,
  labour_activity text not null,
  labour_measure text not null check (labour_measure in ('Unit','Kgs')),
  labour_change boolean,
  labour_service boolean,
  labour_crop_id bigint,
  labour_budget_value numeric,
  labour_department_id bigint references public.labour_department_v2(labour_department_id),
  not_ao boolean,
  active boolean not null default true
);
create table if not exists public.labour_transaction_v2 (
  labour_id bigint generated by default as identity primary key,
  labour_date date not null,
  tracecode_id bigint references public.tracecode(tracecode_id),
  labour_activity_id bigint not null references public.labour_activity_v2(labour_activity_id),
  labour_qty numeric(14,3) not null check(labour_qty >= 0),
  kgs numeric(14,3) check(kgs is null or kgs >= 0),
  labour_unit_cost numeric(14,4) not null check(labour_unit_cost >= 0),
  crop_id bigint references public.crop(crop_id),
  legacy_access_id bigint unique,
  notes text,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid(),
  updated_at timestamptz not null default now()
);
create index if not exists labour_transaction_v2_date_idx on public.labour_transaction_v2(labour_date desc);
create index if not exists labour_transaction_v2_trace_idx on public.labour_transaction_v2(tracecode_id,labour_date desc);
create table if not exists public.labour_budget_v2 (
  labour_budget_id bigint generated by default as identity primary key,
  crop_id bigint not null references public.crop(crop_id),
  irrigation_type_id bigint references public.irrigation_type(irrigation_type_id),
  dap integer not null,
  labour_activity_id bigint not null references public.labour_activity_v2(labour_activity_id),
  budget_qty numeric not null,
  legacy_access_id bigint unique
);
create or replace view public.labour_cost_v2 with (security_invoker=true) as
select t.*, a.labour_activity, a.labour_measure, a.not_ao,
 case when a.labour_measure='Kgs' then coalesce(t.kgs,0)*t.labour_unit_cost
 else t.labour_qty*t.labour_unit_cost end as total_cost,
 case when a.labour_measure='Kgs' and t.labour_qty>0 then t.kgs/t.labour_qty
 else null end as kgs_per_person,
 case when tr.tracecode_size>0 then
 (case when a.labour_measure='Kgs' then coalesce(t.kgs,0)*t.labour_unit_cost
 else t.labour_qty*t.labour_unit_cost end)/tr.tracecode_size
 else null end as cost_per_ha
from public.labour_transaction_v2 t
join public.labour_activity_v2 a on a.labour_activity_id=t.labour_activity_id
left join public.tracecode tr on tr.tracecode_id=t.tracecode_id;
alter table public.labour_department_v2 enable row level security;
alter table public.labour_activity_v2 enable row level security;
alter table public.labour_transaction_v2 enable row level security;
alter table public.labour_budget_v2 enable row level security;
-- IMPORTANT: No broad default access policies here. Add policies aligned to
-- the JSPL app's actual authorization scheme before enabling user access.
commit;
